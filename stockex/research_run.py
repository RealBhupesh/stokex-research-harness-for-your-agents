"""Reproducible local artifact bundles for agent-supplied research reviews."""

import hashlib
import json
import re
from pathlib import Path

from .operations import atomic_json
from .providers.upstox import strict_json
from .research import build_evidence_packet, synthesize_research
from .store.database import PointInTimeStore
from .store.records import normalize_timestamp


MAX_ARTIFACT_BYTES = 16 * 1024 * 1024
BUNDLE_VERSION = 1


def _read_json(path):
    path = Path(path)
    with path.open("rb") as handle:
        raw = handle.read(MAX_ARTIFACT_BYTES + 1)
    if len(raw) > MAX_ARTIFACT_BYTES:
        raise ValueError("Research artifact exceeds the 16 MiB limit")
    return strict_json(raw)


def _checksum(path):
    with Path(path).open("rb") as handle:
        raw = handle.read(MAX_ARTIFACT_BYTES + 1)
    if len(raw) > MAX_ARTIFACT_BYTES:
        raise ValueError("Research artifact exceeds the 16 MiB limit")
    return hashlib.sha256(raw).hexdigest()


def _from_store(config, base):
    if not isinstance(config, dict) or set(config) - {
        "database", "security_id", "cutoff", "fields", "metadata", "mandate", "decision_context"
    } or not {"database", "security_id", "cutoff", "metadata", "mandate"} <= set(config):
        raise ValueError("Evidence-store input requires database, security_id, cutoff, metadata and mandate")
    if not isinstance(config["database"], str) or not isinstance(config["security_id"], str):
        raise ValueError("Evidence database and security_id must be strings")
    database = Path(config["database"])
    if not database.is_absolute():
        database = base / database
    if not database.is_file():
        raise FileNotFoundError(f"Evidence database does not exist: {database}")
    metadata = dict(config["metadata"])
    cutoff = normalize_timestamp(config["cutoff"], "cutoff")
    if "research_cutoff" in metadata and normalize_timestamp(metadata["research_cutoff"], "research_cutoff") != cutoff:
        raise ValueError("Metadata research_cutoff disagrees with evidence-store cutoff")
    metadata["research_cutoff"] = cutoff
    metadata["security_id"] = config["security_id"]
    with PointInTimeStore.open(database) as store:
        if store._security_as_of(config["security_id"], cutoff) is None:
            raise ValueError("Requested evidence security does not exist at the cutoff")
        packet = store.evidence_packet(config["security_id"], cutoff, config.get("fields"))
    controls = [{"kind": "STORE_CONFLICT", "detail": item} for item in packet["conflicts"]]
    controls += [{"kind": "MISSING_FIELD", "field": field} for field in packet["gaps"]]
    return build_evidence_packet(metadata, config["mandate"], packet["sources"], packet["observations"],
                                 controlling_evidence=controls, decision_context=config.get("decision_context"))


def run_research(source, output):
    """Freeze supplied inputs and write a complete or blocked research bundle.

    No reports are generated by an LLM here. The supplied five specialist reports
    and independent review are checked against immutable cutoff evidence.
    """
    source, output = Path(source), Path(output)
    supplied = _read_json(source)
    if not isinstance(supplied, dict) or set(supplied) - {
        "evidence_packet", "evidence", "reports", "skeptical_review", "synthetic_example"
    } or not {"reports", "skeptical_review"} <= set(supplied):
        raise ValueError("Research input requires reports, skeptical_review and one evidence source")
    if ("evidence_packet" in supplied) == ("evidence" in supplied):
        raise ValueError("Supply exactly one of evidence_packet or evidence store configuration")
    packet = supplied.get("evidence_packet") if "evidence_packet" in supplied else _from_store(supplied["evidence"], source.parent)
    frozen = {"evidence_packet": packet, "reports": supplied["reports"], "skeptical_review": supplied["skeptical_review"]}
    if "synthetic_example" in supplied:
        if type(supplied["synthetic_example"]) is not bool:
            raise ValueError("synthetic_example must be a boolean")
        frozen["synthetic_example"] = supplied["synthetic_example"]
    result = synthesize_research(packet, supplied["reports"], supplied["skeptical_review"])
    output.mkdir(mode=0o700, exist_ok=False)
    # A failed/crashed write leaves an incomplete directory. Only the final
    # manifest makes a bundle verifiable; it is never reused or overwritten.
    atomic_json(output / "input.json", frozen)
    atomic_json(output / "result.json", result)
    manifest = {"bundle_version": BUNDLE_VERSION, "kind": "research-synthesis",
                "files": {name: _checksum(output / name) for name in ("input.json", "result.json")},
                "evidence_digest": result["evidence_digest"],
                "status": "PASS" if result["valid"] else "BLOCKED"}
    atomic_json(output / "manifest.json", manifest)
    return {"output": str(output.resolve()), "status": manifest["status"],
            "evidence_digest": result["evidence_digest"], "decision": result["decision"],
            "errors": result["errors"], "assurance": result["assurance"],
            "synthetic_example": frozen.get("synthetic_example", False)}


def verify_research_bundle(directory):
    """Check hashes and replay deterministic synthesis; not an authenticity proof."""
    directory = Path(directory)
    if (directory / "manifest.json").is_symlink():
        raise ValueError("Research manifest must be a regular artifact, not a symlink")
    manifest = _read_json(directory / "manifest.json")
    if not isinstance(manifest, dict) or type(manifest.get("bundle_version")) is not int \
            or manifest.get("bundle_version") != BUNDLE_VERSION \
            or manifest.get("kind") != "research-synthesis" \
            or not isinstance(manifest.get("files"), dict) \
            or set(manifest["files"]) != {"input.json", "result.json"} \
            or any(not isinstance(value, str) or not re.fullmatch(r"[0-9a-f]{64}", value)
                   for value in manifest.get("files", {}).values()):
        raise ValueError("Invalid research bundle manifest")
    errors = []
    for name, digest in manifest["files"].items():
        if (directory / name).is_symlink() or _checksum(directory / name) != digest:
            errors.append({"code": "ARTIFACT_HASH_MISMATCH", "path": name})
    if not errors:
        supplied = _read_json(directory / "input.json")
        stored = _read_json(directory / "result.json")
        if not isinstance(supplied, dict) or not {"evidence_packet", "reports", "skeptical_review"} <= set(supplied):
            raise ValueError("Frozen research input is missing required evidence and review fields")
        replay = synthesize_research(supplied["evidence_packet"], supplied["reports"], supplied["skeptical_review"])
        if replay != stored:
            errors.append({"code": "REPLAY_MISMATCH", "path": "result.json"})
        if replay["evidence_digest"] != manifest.get("evidence_digest") \
                or manifest.get("status") != ("PASS" if replay["valid"] else "BLOCKED"):
            errors.append({"code": "MANIFEST_RESULT_MISMATCH", "path": "manifest.json"})
    return {"valid": not errors, "status": "VERIFIED" if not errors else "BLOCKED", "errors": errors,
            "assurance": "Content integrity and deterministic replay only; not source or reviewer authentication."}
